class ProjectivePhaseObstruction(Task):
    summary = ("Decide whether integer phase defects on the relations of a "
               "generator/relation group can be jointly annihilated by a "
               "globally consistent rephasing modulo a single modulus: report "
               "the minimal m >= 2 that works or 'never' for irreducible "
               "obstructions, across varied generator/relation counts and "
               "coefficient and defect magnitudes.")
    config_cls = ProjectivePhaseObstructionV2Config
    design_choice = ("Instances present a nonabelian group by generators and "
                     "relations with a phase function on a generating set; "
                     "answer is the minimal positive integer m such that the "
                     "phase can be consistently rephased modulo m, or 'never' "
                     "if none exists.")

    def generate_entry(self):
        cfg = self.config
        while True:
            k = cfg.n_gen
            cmax = cfg.coeff_max
            dmax = cfg.defect_max
            rows = []
            for _ in range(k):
                row = [random.randint(-cmax, cmax) for _ in range(k)]
                row[random.randrange(k)] = random.choice((-1, 1)) * random.randint(1, cmax)
                rows.append(row)
            rows[0][0] = random.choice((-1, 1)) * cmax
            defects = [random.randint(-dmax, dmax) for _ in range(k)]
            if random.random() < cfg.never_prob:
                central = random.choice((-1, 1))
            else:
                central = random.choice(_PRIMES) * random.choice((-1, 1))
            pos = random.randrange(1, k)
            rows.insert(pos, [0] * k)
            defects.insert(pos, central)
            ans = _answer(rows, defects)
            _verify(rows, defects, ans)
            break
        answer = "never" if ans is None else str(ans)
        metadata = edict(payload={
            "k": k,
            "rows": rows,
            "defects": defects,
        })
        return Entry(metadata=metadata, answer=answer)

