def _divisors(n):
    if n is None or n < 2:
        return []
    return [d for d in range(2, n + 1) if n % d == 0]


def _solvable(rows, defects, m):
    """Exact: row vector A.tau == -defects (mod m) solvable in Z^k."""
    A = Matrix(rows)
    D, U, _V = smith_normal_decomp(A)
    r = A.shape[0]
    c = U * (-Matrix(defects))
    for i in range(r):
        si = int(D[i, i]) if i < D.shape[1] else 0
        ci = int(c[i])
        if si == 0:
            if ci != 0 and ci % m != 0:
                return False
        else:
            if ci % math.gcd(si, m) != 0:
                return False
    return True


def _answer(rows, defects):
    """Return minimal m >= 2 making A.tau == -d (mod m) solvable, or None
    ('never') if no such modulus exists."""
    A = Matrix(rows)
    D, U, _V = smith_normal_decomp(A)
    r = A.shape[0]
    c = U * (-Matrix(defects))
    zero_cis = []
    for i in range(r):
        si = int(D[i, i]) if i < D.shape[1] else 0
        if si == 0:
            zero_cis.append(int(c[i]))
    nonzero = [x for x in zero_cis if x != 0]
    if nonzero:
        G = abs(nonzero[0])
        for x in nonzero[1:]:
            G = math.gcd(G, abs(x))
    else:
        G = None
    cands = _divisors(G) if G is not None else list(range(2, 121))
    for m in cands:
        if _solvable(rows, defects, m):
            return m
    return None


def _verify(rows, defects, answer):
    """Assert the computed answer is correct (full check in generate_entry)."""
    if answer is None:
        A = Matrix(rows)
        D, U, _V = smith_normal_decomp(A)
        c = U * (-Matrix(defects))
        G = None
        nz = []
        for i in range(A.shape[0]):
            si = int(D[i, i]) if i < D.shape[1] else 0
            if si == 0:
                ci = int(c[i])
                if ci != 0:
                    nz.append(ci)
        if nz:
            G = abs(nz[0])
            for x in nz[1:]:
                G = math.gcd(G, abs(x))
        if G is not None and G < 2:
            return  # structurally impossible, nothing to check
        hi = G if (G is not None and G >= 2) else 120
        for m in range(2, hi + 1):
            assert not _solvable(rows, defects, m), "never but m=%d works" % m
    else:
        assert _solvable(rows, defects, answer), "answer %d should work" % answer
        for m in range(2, answer):
            assert not _solvable(rows, defects, m), (
                "smaller modulus %d works, answer should be %d" % (m, answer))


