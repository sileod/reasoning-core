"""Projective phase obstruction (v2).

Decide whether integer phase defects on the relations of a generator/relation
group can be jointly annihilated by a globally consistent rephasing modulo a
single modulus m >= 2, packaging the linear-congruence obstruction exactly.

Phase model
-----------
A group G is generated by x_1..x_k with relations R_1..R_r.  A projective phase
assigns each generator a phase and thereby induces on every relation a phase
defect.  Writing the j-th relation's signed multiplicities as an integer vector
a_j = (a_{j1}..a_{jk}) and its phase defect as d_j, a rephasing adds an integer
tau_i to generator i's phase, turning d_j into d_j + sum_i a_{ji} tau_i.

The phase is *consistently rephased modulo m* when integers tau_1..tau_k exist
with d_j + sum_i a_{ji} tau_i == 0 (mod m) for every relation j,
i.e. A.tau == -d (mod m), A = [a_1..a_r]^T.

The answer is the smallest integer m >= 2 for which that congruence system is
solvable, or "never" when no such modulus exists (an obstruction of order 1,
meaning the defect gcd is 1, which no rephasing can remove).

Solvability reduction (exact, via Smith normal form)
----------------------------------------------------
Write A = U.D.V with D diagonal (Smith normal form).  Then A.tau == -d (mod m)
is solvable iff, with c = U.(-d):
  * for every diagonal entry s_i > 0 :  gcd(s_i, m) divides c_i, and
  * for every zero diagonal row      :  m divides c_i.
Any admissible m must therefore divide G = gcd of the nonzero c_i living on
zero diagonal rows, so the minimal valid modulus lies among the divisors of G
(or does not exist, in which case the answer is "never").
"""

