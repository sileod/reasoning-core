class QuadraticEnergySignature(Task):
    summary = "Compute the inertia signature (positive, negative, null directions) of rational dense symmetric integer energy matrices with cross terms and degeneracies, invariant under invertible real coordinate changes, with norms drawn over rational diagonal forms."
    design_choice = "Present the energy as a dense symmetric integer matrix and require the signature (p,n,z) as three integers, with instances generated by random congruent transforms to hide the diagonal form."
    config_cls = SignatureConfig

    def generate_entry(self):
        size = self.config.size
        while True:
            diag = [random.choice([random.randint(1, 6), -random.randint(1, 6), 0, 0])
                    for _ in range(size)]
            sig = _signature_from_diag(diag)
            gold = f"{sig[0]},{sig[1]},{sig[2]}"

            D = np.diag(diag).astype(float)
            P = np.array([[random.randint(0, 4) for _ in range(size)]
                          for _ in range(size)], dtype=float)
            if abs(np.linalg.det(P)) < 1e-9:
                continue
            M = P @ D @ P.T
            if np.allclose(M, M.T, atol=1e-9):
                break

        entries = M.round().astype(int)
        assert _matrix_signature(entries) == sig, "signature mismatch"

        rows = "\n".join(" ".join(str(int(v)) for v in r) for r in entries)
        prompt = (
            f"A quadratic energy is E(x) = x^T A x where A is the symmetric "
            f"matrix (one row per line):\n{rows}\n"
            f"Under every invertible real change of coordinates the number of "
            f"positive, negative and null directions is invariant (Sylvester's "
            f"law of inertia). Give the invariant signature as three integers "
            f"p,n,z separated by commas, e.g. '1,2,0' means one positive, two "
            f"negative and no null directions. The answer is exactly 'p,n,z'."
        )
        return Entry(
            metadata={
                "matrix": [[int(v) for v in r] for r in entries],
                "signature": list(sig),
                "prompt": prompt,
            },
            answer=gold,
        )

    def render_prompt(self, metadata):
        return metadata["prompt"]

    def score_answer(self, answer, entry):
        if not isinstance(answer, str):
            return 0.0
        text = answer.strip()
        parts = text.split(",")
        if len(parts) != 3:
            return 0.0
        try:
            got = (int(parts[0].strip()), int(parts[1].strip()), int(parts[2].strip()))
        except ValueError:
            return 0.0
        want = tuple(entry.metadata["signature"])
        return 1.0 if got == want else 0.0
