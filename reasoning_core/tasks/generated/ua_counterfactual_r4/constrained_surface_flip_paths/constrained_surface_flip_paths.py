def _parse_seq(answer):
    s = answer.strip()
    if not s:
        return []
    parts = s.split(';')
    out = []
    for p in parts:
        p = p.strip()
        if not p:
            return None
        if '-' not in p:
            return None
        a, b = p.split('-')
        if not a.isdigit() or not b.isdigit():
            return None
        out.append((int(a), int(b)))
    return out


def _score_impl(answer, metadata):
    if not isinstance(answer, str):
        return 0.0
    parsed = _parse_seq(answer)
    if parsed is None:
        return 0.0
    if len(parsed) != len(metadata['gold_edges']):
        return 0.0
    tris = frozenset(tuple(t) for t in metadata['start_tris'])
    edges = frozenset(tuple(e) for e in metadata['start_edges'])
    marked = frozenset(tuple(e) for e in metadata['marked'])
    forbidden = frozenset(tuple(e) for e in metadata['forbidden'])
    max_deg = metadata['n']
    target_tris = frozenset(tuple(t) for t in metadata['target_tris'])
    for e in parsed:
        e = tuple(sorted(e))
        if e in marked:
            return 0.0
        res = _flip(tris, edges, e, forbidden, max_deg)
        if res is None:
            return 0.0
        tris, edges = res
    return 1.0 if tris == target_tris else 0.0
