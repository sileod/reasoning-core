    config_cls = FlipConfig
    task_version = 2

    def generate_entry(self):
        n = self.config.n
        k = self.config.n_flips
        n_fb = self.config.n_forbidden
        n_mk = self.config.n_marked
        inst = None
        for _ in range(30):
            inst = _make_inst(random, n, k, n_fb, n_mk)
            if inst is not None:
                break
        if inst is None:
            raise RuntimeError('could not sample instance under constraints')
        tris, edges, marked, forbidden, seq = inst
        target_tris, target_edges = _fan_triangulation(n)
        ans = ';'.join(f'{a}-{b}' for a, b in seq)
        return Entry(metadata={
            'n': n,
            'start_tris': [sorted(t) for t in tris],
            'start_edges': [sorted(e) for e in edges],
            'target_tris': [sorted(t) for t in target_tris],
            'target_edges': [sorted(e) for e in target_edges],
            'marked': [sorted(e) for e in marked],
            'forbidden': [sorted(e) for e in forbidden],
            'gold_edges': [list(e) for e in seq],
        }, answer=ans)

