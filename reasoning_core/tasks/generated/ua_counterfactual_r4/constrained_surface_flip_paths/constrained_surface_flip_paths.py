"""Reconfigure triangulated surfaces by legal diagonal flips.

The surface is a triangulated disk (combinatorial 2-complex) whose boundary is
a labeled convex polygon with vertices 0..n-1 in order. A configuration is a
maximal triangulation: the n boundary edges plus n-3 internal diagonals, giving
n-2 triangles. Two adjacent triangles sharing an internal diagonal can be
flipped: the shared diagonal (a,b) is replaced by the other diagonal (c,d) of
the quadrilateral they form. A flip is legal only when, additionally, it
respects the instance constraints: the diagonal to be flipped is not a marked
edge, the replacement diagonal is not a forbidden edge, and no vertex's degree
exceeds the instance max-degree after the flip.

Instances are generated by applying random legal flips forward from a fixed
target triangulation, recording the exact sequence of edge identifiers taken.
The resulting complex is the start; the answer is the shortest sequence of
legal flips (canonical 'a-b' edge identifiers, a<b) that reconfigures the start
back to the target. Minimality is verified by a BFS over the reachable
triangulation graph so the emitted gold sequence is provably shortest.
"""

