def _fan_triangulation(n):
    """Fan triangulation of an n-gon on boundary vertices 0..n-1."""
    tris = []
    edges = set()
    for i in range(1, n - 1):
        tris.append(tuple(sorted((0, i, i + 1))))
    for t in tris:
        ts = sorted(t)
        for i in range(3):
            edges.add(tuple(sorted((ts[i], ts[(i + 1) % 3]))))
    return frozenset(tris), frozenset(edges)


def _other(edge, tri):
    a, b = edge
    for c in tri:
        if c != a and c != b:
            return c
    raise RuntimeError('unreachable')


def _triangle_edges(tri):
    ts = sorted(tri)
    return (tuple(sorted((ts[0], ts[1]))),
            tuple(sorted((ts[1], ts[2]))),
            tuple(sorted((ts[0], ts[2]))))


def _degree(v, tris):
    d = 0
    for t in tris:
        if v in t:
            d += 1
    return d


def _flip(tris, edges, e, forbidden, max_degree):
    """Return (new_tris, new_edges) if flipping edge e is legal under the
    constraints, else None."""
    a, b = e
    shared = [t for t in tris if a in t and b in t]
    if len(shared) != 2:
        return None
    t1, t2 = shared
    c = _other(e, t1)
    d = _other(e, t2)
    if c == d:
        return None
    new_edge = tuple(sorted((c, d)))
    if new_edge in edges:
        return None
    if new_edge in forbidden:
        return None
    if max(_degree(c, tris), _degree(d, tris)) > max_degree:
        return None
    new_tris = [t for t in tris if t != t1 and t != t2]
    new_tris.append(tuple(sorted((a, c, d))))
    new_tris.append(tuple(sorted((b, c, d))))
    new_tris = frozenset(new_tris)
    new_edges = set()
    for t in new_tris:
        for te in _triangle_edges(t):
            new_edges.add(te)
    return new_tris, frozenset(new_edges)


def _legal_flips(tris, edges, marked, forbidden, max_degree):
    out = []
    for e in sorted(edges):
        if e in marked:
            continue
        res = _flip(tris, edges, e, forbidden, max_degree)
        if res is not None:
            out.append((e, res))
    return out


