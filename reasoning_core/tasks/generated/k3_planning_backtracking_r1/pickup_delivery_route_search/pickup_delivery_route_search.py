def manhattan(a, b):
    return abs(a[0] - b[0]) + abs(a[1] - b[1])


def distances(pts):
    n = len(pts)
    d = [[0] * n for _ in range(n)]
    for i in range(n):
        for j in range(n):
            d[i][j] = manhattan(pts[i], pts[j])
    return d


def find_best_route(jobs, capacity):
    """Optimal feasible stop order by memoized exhaustive search.

    A route is a sequence of events (pick up a job / deliver a job) such that
    every pickup precedes its delivery and the in-transit load never exceeds
    capacity. We do a DP over (current event cell, picked mask, delivered mask),
    transitioning to each legal next event, and keep the minimum total cost.
    Among tied-cost optimal routes we keep the lexicographically smallest event
    string. Returns (route_string, cost).
    """
    n = len(jobs)
    start = (0, 0)
    pts = [start] + [cell for job in jobs for cell in job]
    d = distances(pts)
    pidx = [1 + 2 * j for j in range(n)]
    didx = [2 + 2 * j for j in range(n)]

    full = (1 << n) - 1

    def popcount(m):
        return bin(m).count("1")

    from functools import lru_cache

    @lru_cache(maxsize=None)
    def best(cur, picked, delivered):
        # returns (cost, event_string) minimum from this state
        if delivered == full:
            return 0, ""
        load = popcount(picked) - popcount(delivered)
        best_cost = None
        best_str = None
        # deliver a pending job
        for j in range(n):
            if (picked >> j) & 1 and not ((delivered >> j) & 1):
                c2, s2 = best(didx[j], picked, delivered | (1 << j))
                cost = d[cur][didx[j]] + c2
                ev = f"{j}D" + s2
                if best_cost is None or cost < best_cost or (cost == best_cost and ev < best_str):
                    best_cost = cost
                    best_str = ev
        # pick up a job if load allows
        for j in range(n):
            if not ((picked >> j) & 1) and load < capacity:
                c2, s2 = best(pidx[j], picked | (1 << j), delivered)
                cost = d[cur][pidx[j]] + c2
                ev = f"{j}P" + s2
                if best_cost is None or cost < best_cost or (cost == best_cost and ev < best_str):
                    best_cost = cost
                    best_str = ev
        return best_cost, best_str

    cost, route = best(0, 0, 0)
    best.cache_clear()
    return route, cost


@dataclass
class PickupDeliveryConfig(Config):
    grid_size: int = 5
    num_jobs: int = 3
    capacity: int = 2

    def apply_difficulty(self, level):
        self.num_jobs = 2 + min(level, 5)
        self.capacity = 1 + (level // 2)
        self.grid_size = 4 + (level // 2)


class PickupDeliveryRouteSearch(Task):
    summary = "Sequence pickup/delivery stops on a grid with Manhattan distances and a load capacity so each delivery follows its pickup, varying job counts, grid sizes and capacities; answer the shortest feasible stop order (or minimal route cost)."
    config_cls = PickupDeliveryConfig

    def generate_entry(self):
        n = self.config.num_jobs
        g = self.config.grid_size
        cap = self.config.capacity
        while True:
            jobs = []
            for _ in range(n):
                p = (random.randrange(g), random.randrange(g))
                d = (random.randrange(g), random.randrange(g))
                while d == p:
                    d = (random.randrange(g), random.randrange(g))
                jobs.append((p, d))
            route, cost = find_best_route(jobs, cap)
            if route is not None:
                break
        answer = route
        return Entry(
            metadata={
                "jobs": jobs,
                "grid_size": g,
                "capacity": int(cap),
                "route": answer,
                "cost": int(cost),
            },
            answer=answer,
        )

    def render_prompt(self, metadata):
        jobs = metadata["jobs"]
        lines = [
            f"A courier starts at cell (0,0) on a {metadata['grid_size']}x{metadata['grid_size']} grid, moving only horizontally or vertically (Manhattan distance).",
            f"The vehicle carries at most {metadata['capacity']} goods at once. Each job must be picked up at its pickup cell then delivered to its delivery cell; a delivery cannot happen before its pickup.",
            "Jobs:",
        ]
        for i, (p, d) in enumerate(jobs):
            lines.append(f"  Job {i}: pickup {p}, delivery {d}")
        lines.append("Find a sequence of pickups and deliveries that respects the capacity, delivers every job after its pickup, and minimizes total travel. Answer with the stop order as a compact string like '0P1P0D1D' where 'jP' is picking up job j and 'jD' is delivering job j, for the shortest route (ties broken lexicographically).")
        return "\n".join(lines)

    def score_answer(self, answer, entry):
        route = entry.answer
        if not isinstance(answer, str):
            return 0.0
        stripped = "".join(answer.split())
        if stripped == route:
            return 1.0
        return 0.0
