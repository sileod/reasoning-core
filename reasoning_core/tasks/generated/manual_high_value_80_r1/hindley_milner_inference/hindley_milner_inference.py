# ---------------------------------------------------------------------------
# Type representation
# ---------------------------------------------------------------------------


class T:
    __slots__ = ("name",)

    def __init__(self, name):
        self.name = name

    def __repr__(self):
        return self.name


class Arrow:
    __slots__ = ("dom", "cod")

    def __init__(self, dom, cod):
        self.dom = dom
        self.cod = cod

    def __repr__(self):
        return "(%r -> %r)" % (self.dom, self.cod)


class Pair:
    __slots__ = ("a", "b")

    def __init__(self, a, b):
        self.a = a
        self.b = b

    def __repr__(self):
        return "(%r * %r)" % (self.a, self.b)


class Unifier(object):
    """Substitution over explicit type variables (union-find style)."""

    def __init__(self):
        self.bind = {}
        self.n = 0

    def fresh(self, base="t"):
        name = "%s%d" % (base, self.n)
        self.n += 1
        v = T(name)
        self.bind[name] = v
        return v

    def deref(self, t):
        seen = 0
        while isinstance(t, T):
            nxt = self.bind.get(t.name)
            if nxt is None or nxt is t:
                break
            t = nxt
            seen += 1
            if seen > 10000:
                break
        return t

    def prune(self, t):
        t = self.deref(t)
        if isinstance(t, Arrow):
            t.dom = self.prune(t.dom)
            t.cod = self.prune(t.cod)
        elif isinstance(t, Pair):
            t.a = self.prune(t.a)
            t.b = self.prune(t.b)
        return t

    def occurs(self, v, t):
        t = self.deref(t)
        if isinstance(t, T):
            return t is v
        if isinstance(t, Arrow):
            return self.occurs(v, t.dom) or self.occurs(v, t.cod)
        if isinstance(t, Pair):
            return self.occurs(v, t.a) or self.occurs(v, t.b)
        return False

    def unify(self, a, b):
        a = self.deref(a)
        b = self.deref(b)
        if isinstance(a, T) and isinstance(b, T) and a.name == b.name:
            return
        if isinstance(a, T):
            if self.occurs(a, b):
                raise ValueError("occurs check failed")
            self.bind[a.name] = b
            return
        if isinstance(b, T):
            if self.occurs(b, a):
                raise ValueError("occurs check failed")
            self.bind[b.name] = a
            return
        if isinstance(a, Pair) and isinstance(b, Pair):
            self.unify(a.a, b.a)
            self.unify(a.b, b.b)
            return
        if isinstance(a, Arrow) and isinstance(b, Arrow):
            self.unify(a.dom, b.dom)
            self.unify(a.cod, b.cod)
            return
        raise ValueError("structure clash in unify")


def _collect_vars(t, out):
    if isinstance(t, T):
        out.add(t.name)
    elif isinstance(t, Arrow):
        _collect_vars(t.dom, out)
        _collect_vars(t.cod, out)
    elif isinstance(t, Pair):
        _collect_vars(t.a, out)
        _collect_vars(t.b, out)


def _alpha_equal(a, b, u):
    a = u.prune(u.deref(a))
    b = u.prune(u.deref(b))
    if isinstance(a, T) and isinstance(b, T):
        return a.name == b.name
    if isinstance(a, Pair) and isinstance(b, Pair):
        return _alpha_equal(a.a, b.a, u) and _alpha_equal(a.b, b.b, u)
    if isinstance(a, Arrow) and isinstance(b, Arrow):
        return _alpha_equal(a.dom, b.dom, u) and _alpha_equal(a.cod, b.cod, u)
    return False


def _instantiate(ty, free_set, u):
    """Return a copy of ty where each variable in free_set is replaced by a
    fresh variable; variables outside free_set are kept (rendered rigid)."""
    memo = {}

    def go(t):
        if isinstance(t, T):
            if t.name in free_set:
                if t.name not in memo:
                    memo[t.name] = u.fresh("t")
                return memo[t.name]
            return t
        if isinstance(t, Arrow):
            return Arrow(go(t.dom), go(t.cod))
        if isinstance(t, Pair):
            return Pair(go(t.a), go(t.b))
        return t

    return go(ty)


def _clone(ty, u):
    """Structural clone with every variable freshened; returns (newtype, map)."""
    memo = {}

    def go(t):
        if isinstance(t, T):
            if t.name not in memo:
                memo[t.name] = u.fresh("t")
            return memo[t.name]
        if isinstance(t, Arrow):
            return Arrow(go(t.dom), go(t.cod))
        if isinstance(t, Pair):
            return Pair(go(t.a), go(t.b))
        return t

    return go(ty)


def _ref_ok(u, a, b):
    """True if a and b can be unified without triggering an occurs check or a
    structural clash (i.e. the reference of an existing variable of type b for
    a target of type a is safe)."""
    a = u.deref(a)
    b = u.deref(b)
    if isinstance(a, T) and isinstance(b, T):
        return a.name == b.name or not (u.occurs(a, b) or u.occurs(b, a))
    if isinstance(a, T):
        return not u.occurs(a, b)
    if isinstance(b, T):
        return not u.occurs(b, a)
    if isinstance(a, Arrow) and isinstance(b, Arrow):
        return _ref_ok(u, a.dom, b.dom) and _ref_ok(u, a.cod, b.cod)
    if isinstance(a, Pair) and isinstance(b, Pair):
        return _ref_ok(u, a.a, b.a) and _ref_ok(u, a.b, b.b)
    return False


