def _parse(code):
    n = len(code)
    pos = [0]

    def ws():
        while pos[0] < n and code[pos[0]].isspace():
            pos[0] += 1

    def peek():
        ws()
        return code[pos[0]] if pos[0] < n else ""

    def name():
        ws()
        s = pos[0]
        while pos[0] < n and (code[pos[0]].isalnum() or code[pos[0]] == "_"):
            pos[0] += 1
        return code[s:pos[0]]

    def atom():
        ws()
        if peek() == "(":
            return group()
        return ("var", name())

    def group():
        pos[0] += 1  # consume (
        ws()
        if peek() == "\\":
            t = lam()
        elif code.startswith("let", pos[0]) and (pos[0] + 3 >= n or code[pos[0] + 3] in " e"):
            t = let_binding()
        else:
            t = parse_term()
        ws()
        if peek() == ")":
            pos[0] += 1
        return t

    def lam():
        pos[0] += 1  # consume backslash
        nm = name()
        ws()
        if peek() == ".":
            pos[0] += 1
        body = parse_term()
        return ("lam", nm, body)

    def let_binding():
        pos[0] += 3  # consume "let"
        nm = name()
        ws()
        if peek() == "=":
            pos[0] += 1
        val = parse_term()
        ws()
        if code.startswith("in", pos[0]):
            pos[0] += 2
        body = parse_term()
        return ("let", nm, val, body)

    def app_chain(first):
        chain = [first]
        while True:
            ws()
            save = pos[0]
            if peek() == ")":
                break
            if code.startswith("in", pos[0]):
                break
            if peek() == ",":
                break
            t = atom()
            if pos[0] == save:
                break
            chain.append(t)
        node = chain[-1]
        for prev in reversed(chain[:-1]):
            node = ("app", prev, node)
        return node

    def parse_term():
        ws()
        c = peek()
        if c == "\\":
            return lam()
        if c == "(":
            pos[0] += 1
            ws()
            if peek() == "\\":
                t = lam()
                ws()
                if peek() == ")":
                    pos[0] += 1
            elif code.startswith("let", pos[0]) and (pos[0] + 3 >= n or code[pos[0] + 3] in " e"):
                t = let_binding()
                ws()
                if peek() == ")":
                    pos[0] += 1
            elif peek() == ")":
                pos[0] += 1
            else:
                first = parse_term()
                ws()
                if peek() == ",":
                    pos[0] += 1
                    b = parse_term()
                    ws()
                    if peek() == ")":
                        pos[0] += 1
                    t = ("pair", first, b)
                else:
                    t = app_chain(first)
                    ws()
                    if peek() == ")":
                        pos[0] += 1
            return t
        return ("var", name())

    tree = parse_term()
    fv = set()
    bound = set()

    def walk(t):
        if t[0] == "var":
            if t[1] not in bound:
                fv.add(t[1])
        elif t[0] == "lam":
            bound.add(t[1])
            walk(t[2])
            bound.discard(t[1])
        elif t[0] == "app":
            walk(t[1])
            walk(t[2])
        elif t[0] == "pair":
            walk(t[1])
            walk(t[2])
        elif t[0] == "let":
            bound.add(t[1])
            walk(t[2])
            walk(t[3])
            bound.discard(t[1])

    walk(tree)
    return tree, fv


# ---------------------------------------------------------------------------
# Inference: algorithm W with let-generalisation
# ---------------------------------------------------------------------------


class Infer(object):
    def __init__(self, u, sig_env):
        self.u = u
        self.sig_env = sig_env
        self.env = dict(sig_env)

    def generalizable(self, ty):
        sig_free = set()
        for t in self.sig_env.values():
            _collect_vars(t, sig_free)
        local = set()
        _collect_vars(ty, local)
        return local - sig_free

    def run(self, tree):
        node = tree[0]
        u = self.u
        if node == "var":
            nm = tree[1]
            ty = self.env.get(nm)
            if ty is None:
                raise ValueError("unbound variable %s" % nm)
            return ty
        if node == "lam":
            _, nm, body = tree
            vt = u.fresh("t")
            old = self.env.get(nm)
            self.env[nm] = vt
            bt = self.run(body)
            if old is None:
                del self.env[nm]
            else:
                self.env[nm] = old
            return Arrow(vt, bt)
        if node == "app":
            _, f, e = tree
            ft = self.run(f)
            et = self.run(e)
            res = u.fresh("t")
            u.unify(ft, Arrow(et, res))
            return res
        if node == "pair":
            _, a, b = tree
            return Pair(self.run(a), self.run(b))
        if node == "let":
            _, nm, val, body = tree
            vt = self.run(val)
            gen = self.generalizable(vt)
            self.env[nm] = _instantiate(vt, gen, u)
            bt = self.run(body)
            return bt
        raise ValueError("bad node %s" % node)


