"""Principal type inference for a small typed lambda calculus with let.

A well-typed expression is generated by type-directed construction: every
generated term carries the concrete type that the typing rules force, so the
expression is well typed by construction. Each free variable is introduced with
a distinct signature type built from the atoms A, B, C and fresh type
variables; the signature environment (free variable -> type) is fixed. Given
that fixed environment, the type of the whole expression is a deterministic
function of the AST, so an independent Hindley-Milner inference (algorithm W
with let-generalisation over variables not free in the signature) yields the
principal type. The generator checks that its own concrete annotation is an
instance of the inferred principal type and that re-running inference is
stable, then emits the canonical rendering.

Answer format: a canonical type string over atom names A, B, C and type
variables t0, t1, ..., function arrows "\u2192", pairs with "*", and automatic
parenthesisation. Any lexically equal type renders to one unique string.
"""

