@dataclass
class HindleyMilnerConfig(Config):
    maxdepth: int = 2

    def apply_difficulty(self, level):
        self.maxdepth = stochastic_rounding(2 + level)


class HindleyMilnerInference(Task):
    summary = (
        "Infer principal types for small typed lambda expressions with "
        "application, abstraction, tuples, and let-bound polymorphism, "
        "returning a canonical type string over atoms A/B/C and type variables."
    )
    config_cls = HindleyMilnerConfig

    def _build(self):
        """Produce one verified instance, or None if the principal type is too
        trivial (a bare type variable) or the checks fail. Returns an Entry."""
        u = Unifier()
        code, cty, sig_env = Gen(u, self.config.maxdepth).build()

        tree, fv_names = _parse(code)
        if set(sig_env.keys()) != fv_names:
            return None

        # Inferred principal type over the fixed signature environment.
        oh = Unifier()
        sig2 = {nm: _clone(ty, oh) for nm, ty in sig_env.items()}
        inf = Infer(oh, sig2)
        ptype = oh.prune(inf.run(tree))

        # Stability: re-running inference yields an alpha-equal principal type.
        oh2 = Unifier()
        sig2b = {nm: _clone(ty, oh2) for nm, ty in sig_env.items()}
        p2 = oh2.prune(Infer(oh2, sig2b).run(tree))
        if not (_alpha_equal(ptype, p2, oh2) or _alpha_equal(ptype, p2, oh)):
            return None

        # Sanity: the generated concrete type must be an instance of the
        # principal type (unify succeeds on alpha-renamed copies).
        cu = Unifier()
        cp = _clone(ptype, cu)
        cc = _clone(cty, cu)
        try:
            cu.unify(cp, cc)
        except ValueError:
            return None

        ans = _render_answer(ptype, oh)
        # Keep the answer label signature-diverse: reject answers that collapse
        # to a single bare type variable so no level is a constant label.
        if "->" not in ans and "*" not in ans:
            return None
        metadata = {
            "expr": code,
            "signature": {
                nm: _render(ty, oh)
                for nm, ty in sorted(sig_env.items())
            },
            "answer_type": ans,
        }
        return Entry(metadata=metadata, answer=ans)

    def generate_entry(self):
        for _ in range(60):
            ent = self._build()
            if ent is not None:
                return ent
        raise RuntimeError("could not build a structured inference instance")

    def render_prompt(self, metadata):
        sigs = ", ".join(
            "%s : %s" % (nm, ty) for nm, ty in sorted(metadata["signature"].items())
        )
        if not sigs:
            sigs = "(none)"
        return (
            "Using Hindley-Milner type inference, find the most general "
            "(principal) type of the following lambda expression.\n"
            "Environment (types of the free variables), using atoms A, B, C "
            "and type variables a0, a1, ...:\n%s\n"
            "Expression: %s\n"
            "Give the principal type of the expression in a canonical form "
            "using atoms A/B/C and type variables t0, t1, ... (renamed in "
            "order of first appearance), arrows written '->' and pairs with "
            "'*', with parentheses only where needed. For example, the arrow "
            "overs the pair (t0 * A) -> t1 is (t0 * A) -> t1, and A -> B -> t0 "
            "goes: A -> B -> t0. Answer with the type only."
            % (sigs, metadata["expr"])
        )

    def score_answer(self, answer, entry):
        if not isinstance(answer, str):
            return 0.0
        expect = entry.metadata.get("answer_type")
        if expect is None:
            expect = entry.metadata.get("answer", "")
        return 1.0 if answer.strip() == expect else 0.0


