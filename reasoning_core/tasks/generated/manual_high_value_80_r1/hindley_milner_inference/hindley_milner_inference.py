# Rendering
# ---------------------------------------------------------------------------


def _render(ty, u):
    """Canonical rendering. Arrow binds weaker than pair, pair weaker than
    atom; parentheses added only where precedence would change meaning."""
    ty = u.prune(u.deref(ty))

    def go(t, prec):
        t = u.deref(t)
        if isinstance(t, T):
            return t.name
        if isinstance(t, Pair):
            s = "%s * %s" % (go(t.a, 1), go(t.b, 1))
            s = "(%s)" % s
            return s
        if isinstance(t, Arrow):
            s = "%s -> %s" % (go(t.dom, 2), go(t.cod, 1))
            return "(%s)" % s if prec > 0 else s
        return "?"

    return go(ty, 0)


def _render_answer(ty, u):
    """Render principal result with deterministic variable renaming: the first
    occurrence of each type variable is renamed to t0, t1, ... in order of
    first appearance, so alpha-equivalent types share one string. Parentheses
    follow the precedence arrow (weakest) < pair < atom: a nested arrow or a
    pair inside an arrow domain or inside a pair component is parenthesised,
    and an arrow inside a pair domain is parenthesised."""
    ty = u.prune(u.deref(ty))
    ren = {}
    order = []

    def canon(t, prec):
        t = u.deref(t)
        if isinstance(t, T):
            if t.name not in ren:
                ren[t.name] = "t%d" % len(order)
                order.append(t.name)
            return ren[t.name]
        if isinstance(t, Pair):
            s = "%s * %s" % (canon(t.a, 1), canon(t.b, 1))
            return "(%s)" % s
        if isinstance(t, Arrow):
            s = "%s -> %s" % (canon(t.dom, 2), canon(t.cod, 1))
            return s if prec <= 0 else "(%s)" % s
        return "?"

    return canon(ty, 0)


