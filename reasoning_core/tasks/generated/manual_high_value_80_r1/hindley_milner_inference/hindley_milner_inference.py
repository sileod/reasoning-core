def _sig_type(u):
    k = random.randint(0, 4)
    if k == 0:
        return _gen_pair(u, 1)
    if k == 1:
        return _gen_arrow(u, 1)
    return u.fresh("a")


def _gen_pair(u, depth):
    a = _gen_arrow(u, depth)
    b = _gen_arrow(u, depth)
    return Pair(a, b)


def _gen_arrow(u, depth):
    if depth <= 0 or random.random() < 0.4:
        return u.fresh("a")
    return Arrow(_gen_arrow(u, depth - 1), _gen_arrow(u, depth - 1))


class Gen(object):
    """Type-directed well-typed expression builder.

    types: dict name -> current concrete type of every name in scope.
    used: set of all names ever created (so free and bound names never alias).
    """

    def __init__(self, u, maxdepth):
        self.u = u
        self.maxdepth = maxdepth
        self.types = {}
        self.used = set()
        self.vseq = 0
        self.names = [
            "w", "x", "y", "z", "m", "n", "p", "q", "f", "g", "h",
            "a", "b", "c", "k", "j", "r", "s", "tval", "pair", "fn",
        ]

    def _freshname(self, avoid):
        pool = [n for n in self.names if n not in self.used and n not in avoid]
        if pool:
            nm = random.choice(pool)
            self.used.add(nm)
            return nm
        self.vseq += 1
        nm = "v%d" % self.vseq
        self.used.add(nm)
        return nm

    def _candidates(self, avoid):
        # names currently in scope (bound or free-introduced), excluding avoid
        return sorted(self.types.keys())

    def _leaf(self, target, avoid):
        u = self.u
        cand = self._candidates(avoid)
        if target is not None and cand and random.random() < 0.5:
            # only reference an existing candidate if its type is compatible
            random.shuffle(cand)
            for name in cand:
                ct = self.types[name]
                if _ref_ok(u, target, ct):
                    u.unify(target, ct)
                    return (name, self.types[name])
        if cand and target is None and random.random() < 0.5:
            name = random.choice(cand)
            return (name, self.types[name])
        # introduce a fresh free variable having its own signature type
        v = u.fresh("a")
        nm = self._freshname(avoid)
        if target is not None:
            u.unify(v, target)
        self.types[nm] = v
        return (nm, v)

    def _lam(self, depth, avoid):
        u = self.u
        pty = _sig_type(u)
        nm = self._freshname(avoid)
        self.types[nm] = pty
        body, bty = self._term(depth + 1, None, avoid)
        del self.types[nm]
        return ("(\\%s.%s)" % (nm, body), Arrow(pty, bty))

    def _app(self, depth, avoid):
        u = self.u
        dom = _sig_type(u)
        cod = _sig_type(u)
        f, _ = self._leaf(Arrow(dom, cod), avoid)
        e, _ = self._leaf(dom, avoid)
        return ("(%s %s)" % (f, e), cod)

    def _pair(self, depth, avoid):
        a, aty = self._term(depth + 1, None, avoid)
        b, bty = self._term(depth + 1, None, avoid)
        return ("(%s, %s)" % (a, b), Pair(aty, bty))

    def _let(self, depth, avoid):
        val, vty = self._term(depth + 1, None, avoid)
        nm = self._freshname(avoid)
        self.types[nm] = vty
        body, bty = self._term(depth + 1, None, avoid)
        del self.types[nm]
        return ("(let %s = %s in %s)" % (nm, val, body), bty)

    def _term(self, depth, target, avoid):
        u = self.u
        if depth >= self.maxdepth or random.random() < 0.18:
            return self._leaf(target, avoid)
        r = random.random()
        if r < 0.28:
            return self._lam(depth, avoid)
        if r < 0.52:
            return self._app(depth, avoid)
        if r < 0.72:
            return self._pair(depth, avoid)
        return self._let(depth, avoid)

    def build(self):
        code, ty = self._term(0, None, set())
        sig_env = dict(self.types)
        return code, ty, sig_env


